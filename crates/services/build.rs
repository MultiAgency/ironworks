//! Compile the repo-root service library into the binary: the `scrap/` markdown tree and the `services/`
//! definitions.
//!
//! Both are product decisions rather than operator state, and both are embedded for the same
//! reason. This is why no `resource_root()`-style path guessing exists here. The Python prior art
//! has a four-way fallback — explicit argument, then an environment variable, then a detected
//! checkout root, then a directory inside the installed wheel — because "am I running from a
//! checkout or an install?" is a real question there. Compiled in, it is not a question the
//! program can ask, and there is no deployment in which the answer is wrong.
//!
//! One build script, because it is one boundary: everything this artifact can ever show a model,
//! or serve as a service definition, is decided here and travels with the binary.

use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    scrap(&manifest, &out_dir);
    services(&manifest, &out_dir);
    println!("cargo:rerun-if-changed=build.rs");
}

/// The markdown tree: persona fragments and skills, recursively, by repo-relative path.
fn scrap(manifest: &Path, out_dir: &Path) {
    let root = manifest
        .join("../../scrap")
        .canonicalize()
        .expect("the scrap/ tree must exist at the repo root");

    let mut found = Vec::new();
    collect(&root, &root, &mut found);
    found.sort();
    assert!(!found.is_empty(), "scrap/ holds no markdown; refusing to build an empty heap");

    let mut out = String::from(
        "// @generated by crates/services/build.rs from the repo-root scrap/ tree. Do not edit.\n\
         /// Every piece, sorted by path. Compiled in, so this is the whole heap.\n\
         pub static SCRAP: &[(&str, &str)] = &[\n",
    );
    for (rel, abs) in &found {
        println!("cargo:rerun-if-changed={}", abs.display());
        out.push_str(&format!("    ({:?}, include_str!({:?})),\n", rel, abs.display().to_string()));
    }
    out.push_str("];\n");

    fs::write(out_dir.join("scrap.rs"), out).expect("write generated scrap table");
    println!("cargo:rerun-if-changed={}", root.display());
}

/// The service definitions: flat JSON, keyed by file stem.
///
/// That the filename is the id and the two must agree is checked when a definition is *loaded*,
/// not here. A build script that refused a mismatch would fail the whole build with no good way
/// to say which service is wrong.
fn services(manifest: &Path, out_dir: &Path) {
    let root = manifest
        .join("../../services")
        .canonicalize()
        .expect("the services/ tree must exist at the repo root");

    let mut found = Vec::new();
    for entry in fs::read_dir(&root).expect("read services/") {
        let path = entry.expect("dir entry").path();
        if path.extension().is_some_and(|e| e == "json") {
            let stem = path.file_stem().expect("stem").to_string_lossy().to_string();
            found.push((stem, path));
        }
    }
    found.sort();
    assert!(!found.is_empty(), "services/ holds no definitions");

    let mut out = String::from(
        "// @generated by crates/services/build.rs from the repo-root services/ tree. Do not edit.\n\
         /// Every definition, sorted by name: (name, raw JSON).\n\
         pub static DEFINITIONS: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &found {
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            name,
            path.display().to_string()
        ));
    }
    out.push_str("];\n");

    fs::write(out_dir.join("definitions.rs"), out).expect("write generated definitions table");
    println!("cargo:rerun-if-changed={}", root.display());
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for entry in entries {
        let path = entry.expect("dir entry").path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.extension().is_some_and(|e| e == "md") {
            let rel =
                path.strip_prefix(root).expect("under root").to_string_lossy().replace('\\', "/");
            out.push((rel, path));
        }
    }
}
